"""Generate docs/DECISION_EXAMPLES.md from real runs of the platform.

Uses the real simulated services (with their demo knobs) and a throwaway
database, so every example in the doc is actual system output.

    python scripts/generate_examples.py
"""

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from app.container import Container  # noqa: E402
from app.core.settings import Settings  # noqa: E402
from app.main import create_app  # noqa: E402

LOAN = {
    "applicant_name": "Asha Verma", "age": 32, "monthly_income": 90000,
    "loan_amount": 300000, "employment_type": "salaried", "documents": {"id_proof": "aadhaar-123"},
}

SCENARIOS = [
    ("Loan approved on the fast track", "loan_approval", {"applicant_id": "APP-CS780-001", **LOAN}, None),
    ("Loan rejected for a low credit score", "loan_approval", {"applicant_id": "APP-CS540-002", **LOAN}, None),
    ("Loan sent to manual review: KYC document missing", "loan_approval",
     {"applicant_id": "APP-CS780-003", **LOAN, "documents": {}}, None),
    ("Loan approved after the credit bureau timed out twice", "loan_approval",
     {"applicant_id": "APP-FLAKY-CS720", **LOAN, "loan_amount": 600000}, None),
    ("Loan paused because the credit bureau is down", "loan_approval",
     {"applicant_id": "APP-DOWN-005", **LOAN}, None),
    ("Loan paused because the credit bureau is too slow (deadline)", "loan_approval",
     {"applicant_id": "APP-SLOW-006", **LOAN}, None),
    ("Claim sent to an investigator: medium fraud risk", "claim_processing",
     {"claim_id": "CLM-RISK75-1", "policy_id": "POL-0042", "claim_type": "motor", "policy_active": True,
      "claim_amount": 20000, "policy_coverage": 500000, "documents": {"claim_form": "form-77"}}, None),
    ("Duplicate submission returns the stored decision", "loan_approval",
     {"applicant_id": "APP-CS780-001", **LOAN}, "dup-demo"),
]


def section(title: str, workflow: str, payload: dict, key: str | None, client: TestClient) -> str:
    headers = {"Idempotency-Key": key} if key else {}
    first = client.post(f"/workflows/{workflow}/requests", json=payload, headers=headers)
    response = first
    if key:  # send it again to show the duplicate handling
        response = client.post(f"/workflows/{workflow}/requests", json=payload, headers=headers)

    body = response.json()
    exp = client.get(f"/requests/{body['request_id']}/explanation").json()

    lines = [f"## {title}", "", f"**Workflow:** `{workflow}` v{exp['workflow_version']}", ""]
    lines += ["### Input", "", "```json", json.dumps(payload, indent=2), "```", ""]

    lines += ["### Rules triggered (failed)", ""]
    if exp["rules_triggered"]:
        lines += ["| Rule | Description | Data used | Action |", "|---|---|---|---|"]
        for r in exp["rules_triggered"]:
            data = ", ".join(f"`{d['field']}={d['value']}` ({d['operator']} {d['expected']})" for d in r["data_used"])
            lines.append(f"| {r['rule_id']} | {r['description']} | {data} | **{r['action_taken']}** |")
    else:
        lines.append("None. Every blocking rule passed.")
    lines.append("")

    if exp["rules_passed"]:
        passed = ", ".join(r["rule_id"] for r in exp["rules_passed"])
        lines += [f"**Rules passed:** {passed}", ""]

    if exp["dependency_calls"]:
        lines += ["### External calls", ""]
        for call in exp["dependency_calls"]:
            detail = json.dumps(call.get("response")) if call["outcome"] == "success" else call["error"]
            lines.append(f"- `{call['service']}`: {call['outcome']} after {call['attempts']} attempt(s), {detail}")
        lines.append("")

    lines += ["### Output", "", "```json"]
    output = {k: body[k] for k in ("request_id", "status", "decision", "decision_reason", "current_stage",
                                   "attempt_count", "duplicate")}
    lines += [json.dumps(output, indent=2), "```", ""]
    if key:
        lines += [f"HTTP status of the first call: {first.status_code}. "
                  f"HTTP status of the repeat: {response.status_code}, header "
                  f"`Idempotent-Replayed: {response.headers.get('Idempotent-Replayed')}`.", ""]

    lines += ["### Audit reasoning", "", "```text", *exp["narrative"], "```", ""]
    lines += [f"**Lifecycle:** {' | '.join(exp['lifecycle'])}", "", "---", ""]
    return "\n".join(lines)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(db_path=f"{tmp}/examples.db", workflow_dir=str(ROOT / "config" / "workflows"))
        client = TestClient(create_app(Container.build(settings, sleep=lambda _: None)))

        parts = [
            "# Decision Explanation Examples",
            "",
            "Generated by `python scripts/generate_examples.py` from real runs of the platform. "
            "Each example shows the input, the rules that fired, the output and the audit reasoning. "
            "The same data is available live from `GET /requests/{id}/explanation`.",
            "",
            "Simulator demo knobs used below: `CS<score>` in an applicant id forces that credit score, "
            "`RISK<n>` in a claim id forces that fraud score, `FLAKY` makes the service time out twice, "
            "`SLOW` makes it answer after 5 s (past the 2 s deadline), `DOWN` makes it always unavailable.",
            "",
            "---",
            "",
        ]
        for title, workflow, payload, key in SCENARIOS:
            parts.append(section(title, workflow, payload, key, client))

    out = ROOT / "docs" / "DECISION_EXAMPLES.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
